#!/usr/bin/env node
// TRACE-105: builds src/lib/leeZipMap.ts, the drawn Lee County ZIP map on public provider profiles.
// Shapes are 2020 Census ZCTA boundaries (public domain) from TIGERweb, simplified, for every
// allowlist ZIP that has one; PO-box ZIPs have no ZCTA and are listed but not drawn.
// Run: node scripts/generate-lee-zip-map.mjs
import { readFileSync, writeFileSync } from "node:fs";

const MIGRATION = "supabase/migrations/20260927010000_cfg001_lee_county_coverage.sql";
const OUT = "src/lib/leeZipMap.ts";
const WIDTH = 400;
const SIMPLIFY_DEGREES = 0.0007;

// Map labels: a short name per community, placed at its ZIPs' combined centroid unless overridden.
const LABELS = [
  { name: "Cape Coral", cities: ["Cape Coral"] },
  { name: "Fort Myers", cities: ["Fort Myers"], zips: ["33901", "33916", "33907", "33919"] },
  { name: "N. Fort Myers", cities: ["North Fort Myers"] },
  { name: "Lehigh Acres", cities: ["Lehigh Acres"] },
  { name: "Estero", cities: ["Estero"] },
  { name: "Bonita Springs", cities: ["Bonita Springs"] },
  { name: "Sanibel", cities: ["Sanibel"] },
  { name: "Pine Island", cities: ["Bokeelia", "Saint James City"] },
  { name: "Alva", cities: ["Alva"] },
];

const sql = readFileSync(MIGRATION, "utf8");
const cityByZip = new Map([...sql.matchAll(/\('(\d{5})', '([^']+)', 'FL'/g)].map((m) => [m[1], m[2]]));

const url = new URL("https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/tigerWMS_Current/MapServer/2/query");
url.search = new URLSearchParams({
  where: `ZCTA5 IN (${[...cityByZip.keys()].map((zip) => `'${zip}'`).join(",")})`,
  outFields: "ZCTA5",
  outSR: "4326",
  maxAllowableOffset: String(SIMPLIFY_DEGREES),
  geometryPrecision: "4",
  f: "geojson",
}).toString();
const response = await fetch(url);
if (!response.ok) throw new Error(`TIGERweb returned ${response.status}`);
const features = (await response.json()).features;

const polygons = (geometry) => (geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates);
const points = features.flatMap((f) => polygons(f.geometry).flat(2));
const [minLon, maxLon] = [Math.min(...points.map((p) => p[0])), Math.max(...points.map((p) => p[0]))];
const [minLat, maxLat] = [Math.min(...points.map((p) => p[1])), Math.max(...points.map((p) => p[1]))];
const kx = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const scale = WIDTH / ((maxLon - minLon) * kx);
const height = Math.ceil((maxLat - minLat) * scale);
const project = ([lon, lat]) => [(lon - minLon) * kx * scale, (maxLat - lat) * scale];
const round = (n) => Math.round(n * 10) / 10;

function ringPath(ring) {
  const out = [];
  for (const point of ring.map(project)) {
    const [x, y] = point.map(round);
    if (out.length && out.at(-1)[0] === x && out.at(-1)[1] === y) continue;
    out.push([x, y]);
  }
  return out.length < 3 ? "" : `M${out.map(([x, y]) => `${x} ${y}`).join("L")}Z`;
}

// Signed-area centroid of a ring in projected coordinates.
function ringCentroid(ring) {
  const p = ring.map(project);
  let a = 0, cx = 0, cy = 0;
  for (let i = 0; i < p.length - 1; i++) {
    const cross = p[i][0] * p[i + 1][1] - p[i + 1][0] * p[i][1];
    a += cross; cx += (p[i][0] + p[i + 1][0]) * cross; cy += (p[i][1] + p[i + 1][1]) * cross;
  }
  return { area: Math.abs(a / 2), x: cx / (3 * a), y: cy / (3 * a) };
}

const shapes = features
  .map((f) => ({
    zip: f.properties.ZCTA5,
    d: polygons(f.geometry).flatMap((polygon) => polygon.map(ringPath)).filter(Boolean).join(""),
    centroids: polygons(f.geometry).map((polygon) => ringCentroid(polygon[0])),
  }))
  .sort((a, b) => a.zip.localeCompare(b.zip));

const labels = LABELS.map(({ name, cities, zips }) => {
  const parts = shapes
    .filter((s) => (zips ? zips.includes(s.zip) : cities.includes(cityByZip.get(s.zip))))
    .flatMap((s) => s.centroids);
  const area = parts.reduce((t, c) => t + c.area, 0);
  return {
    name,
    cities,
    x: round(parts.reduce((t, c) => t + c.x * c.area, 0) / area),
    y: round(parts.reduce((t, c) => t + c.y * c.area, 0) / area),
  };
});

writeFileSync(OUT, `// Generated by scripts/generate-lee-zip-map.mjs — do not edit by hand.
// 2020 Census ZCTA boundaries (U.S. Census Bureau TIGERweb, public domain), simplified.
// Shapes only: the coverage_areas allowlist stays authoritative for what is served.

export const LEE_ZIP_MAP_VIEWBOX = { width: ${WIDTH}, height: ${height} } as const;

export const LEE_ZIP_SHAPES: readonly { zip: string; d: string }[] = [
${shapes.map((s) => `  { zip: "${s.zip}", d: "${s.d}" },`).join("\n")}
];

export const LEE_ZIP_MAP_LABELS: readonly { name: string; cities: readonly string[]; x: number; y: number }[] = [
${labels.map((l) => `  { name: "${l.name}", cities: ${JSON.stringify(l.cities)}, x: ${l.x}, y: ${l.y} },`).join("\n")}
];
`);
console.log(`Wrote ${OUT}: ${shapes.length} ZIP shapes, ${WIDTH}x${height}`);
