import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { serviceCategories, services } from "../src/lib/serviceData.ts";

// Node 24 strips the source file's types. Only repository-owned catalog metadata
// is used: no live database query, production pricing, customer or provider data.
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const array = (values) => `ARRAY[${values.map(quote).join(", ")}]::text[]`;
const timestamp = "'2026-01-01T00:00:00Z'::timestamptz";
const categories = serviceCategories.map((category, index) =>
  `  (${[category.id, category.name, category.icon, category.description].map(quote).join(", ")}, ${index}, ${timestamp}, ${timestamp})`,
);
const catalog = services.map((service, index) =>
  `  (${[service.id, service.name, service.categoryId].map(quote).join(", ")}, ${array(service.tags)}, ${quote(service.icon)}, ${quote(service.descriptor)}, ${service.popular === true}, ${quote(service.defaultFrequency)}, ${array(service.availableFrequencies ?? [service.defaultFrequency])}, ${index}, 'custom_quote', ${timestamp}, ${timestamp})`,
);

const sql = `-- Generated by npm run db:seed:generate. Do not hand-edit.
-- Local-only reference metadata from src/lib/serviceData.ts.
-- No users, customer rows, live provider proof, credentials, or production prices.
-- No coverage is asserted. Real offers require eligible vendor packages.
-- Catalog prices stay at their zero defaults; these are sourcing/quote references.

INSERT INTO public.service_categories
  (id, name, icon, description, sort_order, created_at, updated_at)
VALUES
${categories.join(",\n")}
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.services_catalog
  (id, name, category_id, tags, icon, descriptor, is_popular,
   default_frequency, available_frequencies, sort_order, pricing_mode,
   created_at, updated_at)
VALUES
${catalog.join(",\n")}
ON CONFLICT (id) DO NOTHING;

-- Recovered historical migrations contain explicitly labelled sample providers.
-- Keep those historical files intact, but do not present their synthetic ratings
-- and completed-job counts as active supply in a freshly seeded local project.
UPDATE public.contractors
SET is_active = false, marketing_enabled = false, updated_at = ${timestamp}
WHERE user_id IS NULL
  AND name IN (
    'GreenScape Pro', 'CrystalClear Pools', 'SparkleHome Cleaning',
    'FixIt Right Handyman', 'CoolBreeze HVAC', 'BugShield Pest Control',
    'ProFlow Plumbing', 'TopShelf Exteriors'
  );
`;

writeFileSync(fileURLToPath(new URL("../supabase/seed.sql", import.meta.url)), sql);
console.log(`Generated ${serviceCategories.length} categories and ${services.length} service references; no customer or live provider data.`);
